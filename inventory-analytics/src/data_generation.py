def generate_suppliers(rng: np.random.Generator) -> pd.DataFrame:
    """Generate 30 suppliers with realistic ratings, lead times, and statuses."""
    prefixes = [
        "Apex", "Global", "Prime", "Summit", "Vertex", "Pacific", "Atlantic",
        "Pioneer", "Horizon", "Sterling", "Atlas", "Vanguard", "United", "Metro",
        "Dynamic", "Crest", "Beacon", "Harbor", "Meridian", "Keystone",
        "Cascade", "Liberty", "Omega", "Quantum", "Zenith", "Crown", "Bridge",
        "Vector", "Nexus", "Evergreen",
    ]
    suffixes = ["Supply Co.", "Logistics", "Industries", "Distribution", "Imports", "Partners"]
    regions = ["North America", "East Asia", "Europe", "South Asia", "Latin America"]

    records = []
    for i in range(1, 31):
        sid = f"SUP-{i:03d}"
        name = f"{prefixes[i - 1]} {suffixes[i % len(suffixes)]}"
        region = regions[i % len(regions)]
        # Make suppliers 25-29 chronically slower/lower rated for analytical contrast
        if i >= 25:
            rating = round(float(rng.uniform(2.6, 3.4)), 2)
            avg_days = int(rng.integers(14, 24))
            status = "Active" if i < 29 else "On Hold"
        elif i <= 6:
            rating = round(float(rng.uniform(4.5, 4.95)), 2)
            avg_days = int(rng.integers(4, 8))
            status = "Preferred"
        else:
            rating = round(float(rng.uniform(3.6, 4.6)), 2)
            avg_days = int(rng.integers(7, 15))
            status = "Active"

        records.append({
            "supplier_id": sid,
            "supplier_name": name,
            "supplier_region": region,
            "supplier_rating": rating,
            "average_delivery_days": avg_days,
            "supplier_status": status,
        })
    return pd.DataFrame(records)


def generate_products(rng: np.random.Generator, suppliers_df: pd.DataFrame) -> pd.DataFrame:
    """Generate 500 products with velocity tiers (Fast, Normal, Slow, Dead)."""
    cat_names = list(CATEGORIES.keys())
    supplier_ids = suppliers_df["supplier_id"].tolist()
    supplier_lead_map = dict(zip(suppliers_df["supplier_id"], suppliers_df["average_delivery_days"]))

    adjectives = [
        "Pro", "Ultra", "Essential", "Compact", "Smart", "Classic", "Elite",
        "Eco", "Studio", "Flex", "Max", "Air", "Core", "Prime", "Active",
    ]
    nouns_by_sub = {
        "Audio & Headphones": ["Wireless Earbuds", "Studio Headphones", "Bluetooth Speaker", "Soundbar"],
        "Smart Home": ["Smart Plug", "Wi-Fi Camera", "LED Strip", "Thermostat Hub"],
        "Computer Accessories": ["USB-C Hub", "Mechanical Keyboard", "Wireless Mouse", "Laptop Stand"],
        "Small Appliances": ["Air Fryer", "Espresso Maker", "Blender", "Electric Kettle"],
        "Cookware": ["Cast Iron Skillet", "Nonstick Pan Set", "Chef Knife", "Dutch Oven"],
        "Storage & Organization": ["Modular Bin", "Pantry Container Set", "Vacuum Seal Bags", "Spice Rack"],
        "Athletic Wear": ["Compression Tee", "Training Shorts", "Performance Hoodie", "Yoga Leggings"],
        "Outerwear": ["Rain Shell Jacket", "Fleece Pullover", "Insulated Vest", "Windbreaker"],
        "Running Shoes": ["Trail Runner", "Road Cushioned Shoe", "Carbon Tempo Shoe", "Cross Trainer"],
        "Fitness Equipment": ["Adjustable Dumbbell", "Resistance Band Kit", "Kettlebell", "Yoga Mat"],
        "Camping Gear": ["Dome Tent", "Sleeping Bag", "Camp Lantern", "Insulated Flask"],
        "Cycling Accessories": ["Bike Helmet", "LED Tail Light", "U-Lock", "Frame Pump"],
        "Ergonomic Furniture": ["Mesh Office Chair", "Monitor Arm", "Standing Desk Mat", "Footrest"],
        "Paper & Notebooks": ["Hardcover Journal", "Planner Pad", "Copy Paper Ream", "Sticky Note Pack"],
        "Desk Organizers": ["Mesh Tray", "Cable Management Box", "Pen Caddy", "File Sorter"],
        "Skincare": ["Hyaluronic Serum", "SPF50 Moisturizer", "Clay Cleanser", "Night Cream"],
        "Vitamins & Supplements": ["Omega-3 Softgels", "Vitamin D3 Drops", "Electrolyte Mix", "Collagen Powder"],
        "Personal Grooming": ["Electric Trimmer", "Sonic Toothbrush", "Hair Dryer", "Shave Kit"],
    }

    records = []
    for i in range(1, 501):
        pid = f"PRD-{i:04d}"
        cat = cat_names[(i - 1) % len(cat_names)]
        meta = CATEGORIES[cat]
        sub = meta["subcategories"][(i // len(cat_names)) % len(meta["subcategories"])]
        brand = meta["brands"][int(rng.integers(0, len(meta["brands"])))]
        noun_list = nouns_by_sub[sub]
        adj = adjectives[int(rng.integers(0, len(adjectives)))]
        noun = noun_list[int(rng.integers(0, len(noun_list)))]
        product_name = f"{brand} {adj} {noun} {i:03d}"

        unit_cost = round(float(rng.uniform(*meta["cost_range"])), 2)
        margin = float(rng.uniform(*meta["margin_range"]))
        selling_price = round(unit_cost * margin, 2)

        sup_id = supplier_ids[int(rng.integers(0, len(supplier_ids)))]
        lead_time = max(2, int(supplier_lead_map[sup_id] + rng.integers(-2, 4)))

        # Assign demand profile:
        # 1-300: normal/fast; 301-410: high velocity / stockout-prone;
        # 411-470: overstocked / slow-moving; 471-500: dead stock (very low/zero recent sales)
        if i <= 300:
            daily_demand = float(rng.uniform(0.35, 1.8))
        elif i <= 410:
            daily_demand = float(rng.uniform(1.8, 4.2))
        elif i <= 470:
            daily_demand = float(rng.uniform(0.08, 0.30))
        else:
            daily_demand = float(rng.uniform(0.01, 0.05))

        safety_stock = max(12, int(round(daily_demand * lead_time * 1.4)))
        reorder_level = max(safety_stock + 10, int(round(daily_demand * lead_time * 2.2 + safety_stock)))

        records.append({
            "product_id": pid,
            "product_name": product_name,
            "category": cat,
            "subcategory": sub,
            "brand": brand,
            "unit_cost": unit_cost,
            "selling_price": selling_price,
            "reorder_level": reorder_level,
            "safety_stock": safety_stock,
            "lead_time_days": lead_time,
            "supplier_id": sup_id,
        })

    return pd.DataFrame(records)


def generate_transactions(
    rng: np.random.Generator,
    products_df: pd.DataFrame,
    warehouses_df: pd.DataFrame,
    suppliers_df: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Generate reconciled purchase_orders, inventory_movements, and sales."""
    start_dt = datetime.strptime(config.DATA_START_DATE, "%Y-%m-%d")
    end_dt = datetime.strptime(config.DATA_END_DATE, "%Y-%m-%d")
    total_days = (end_dt - start_dt).days + 1

    wh_ids = warehouses_df["warehouse_id"].tolist()
    # Warehouse weights: WH-002 & WH-001 highest volume, WH-005 lowest utilization
    wh_weights = np.array([0.25, 0.28, 0.22, 0.16, 0.09])

    sup_delay_prob = {
        row["supplier_id"]: (0.62 if int(row["supplier_id"].split("-")[1]) >= 25 else 0.14)
        for _, row in suppliers_df.iterrows()
    }

    po_rows = []
    mov_rows = []
    sales_rows = []

    po_counter = 1
    mov_counter = 1
    sale_counter = 1

    # Track exact on-hand stock per (product_id, warehouse_id) to guarantee consistency
    stock_on_hand: dict[tuple[str, str], int] = {}

    # Step 1: Opening stock purchases on day 0-15 so every product-warehouse has initial inventory
    for idx, prod in products_df.iterrows():
        pid = prod["product_id"]
        p_num = int(pid.split("-")[1])
        ucost = float(prod["unit_cost"])
        sup_id = prod["supplier_id"]
        lead = int(prod["lead_time_days"])

        for wh_idx, wid in enumerate(wh_ids):
            # Overstocked tier gets heavy opening stock; stockout-prone gets leaner opening stock
            if p_num > 410 and p_num <= 470:
                init_qty = int(rng.integers(95, 190))
            elif p_num > 470:
                init_qty = int(rng.integers(55, 120))
            elif p_num > 300:
                init_qty = int(rng.integers(12, 32))
            else:
                init_qty = int(rng.integers(20, 55))

            # WH-005 gets slightly lower initial stock
            if wh_idx == 4:
                init_qty = max(15, int(init_qty * 0.65))

            order_dt = start_dt - timedelta(days=int(rng.integers(5, 15)))
            exp_dt = order_dt + timedelta(days=lead)
            act_dt = start_dt + timedelta(days=int(rng.integers(0, 5)))
            po_id = f"PO-{po_counter:06d}"
            po_counter += 1

            po_rows.append({
                "purchase_order_id": po_id,
                "supplier_id": sup_id,
                "product_id": pid,
                "warehouse_id": wid,
                "order_date": order_dt.strftime("%Y-%m-%d"),
                "expected_delivery_date": exp_dt.strftime("%Y-%m-%d"),
                "actual_delivery_date": act_dt.strftime("%Y-%m-%d"),
                "quantity_ordered": init_qty,
                "quantity_received": init_qty,
                "purchase_cost": round(init_qty * ucost, 2),
                "order_status": "Delivered",
            })

            mov_rows.append({
                "movement_id": f"MOV-{mov_counter:06d}",
                "product_id": pid,
                "warehouse_id": wid,
                "movement_date": act_dt.strftime("%Y-%m-%d"),
                "movement_type": "Purchase",
                "quantity": init_qty,
                "unit_cost": ucost,
                "reference_id": po_id,
            })
            mov_counter += 1
            stock_on_hand[(pid, wid)] = init_qty

    # Step 2: Simulate 24 months of sales, replenishments, returns, adjustments, transfers
    # Group into 24 monthly steps for speed and clean seasonality
    for month_idx in range(24):
        m_start = start_dt + timedelta(days=month_idx * 30)
        m_end = min(end_dt, m_start + timedelta(days=29))
        m_days = max(1, (m_end - m_start).days + 1)
        cal_month = m_start.month
        # Seasonality: Q4 peak (Nov/Dec), Q1 soft (Jan/Feb), steady summer
        season_mult = {
            1: 0.78, 2: 0.80, 3: 0.92, 4: 0.96, 5: 1.02, 6: 1.05,
            7: 1.04, 8: 1.08, 9: 1.02, 10: 1.12, 11: 1.32, 12: 1.40,
        }[cal_month]

        for _, prod in products_df.iterrows():
            pid = prod["product_id"]
            p_num = int(pid.split("-")[1])
            ucost = float(prod["unit_cost"])
            sprice = float(prod["selling_price"])
            sup_id = prod["supplier_id"]
            lead = int(prod["lead_time_days"])
            reorder_lvl = int(prod["reorder_level"])

            # Dead stock: zero sales in last 9 months
            if p_num > 470 and month_idx >= 15:
                continue
            # Slow moving: sparse sales
            if p_num > 410 and p_num <= 470 and rng.random() > 0.35:
                continue

            # Pick 1-2 warehouses for sales this month
            n_sales_events = 2 if p_num <= 410 and rng.random() < 0.65 else 1
            if p_num > 470:
                n_sales_events = 1 if rng.random() < 0.25 else 0

            for _ in range(n_sales_events):
                wid = rng.choice(wh_ids, p=wh_weights)
                avail = stock_on_hand[(pid, wid)]
                if avail <= 0:
                    continue

                if p_num <= 300:
                    base_qty = int(rng.integers(5, 22))
                elif p_num <= 410:
                    base_qty = int(rng.integers(8, 32))
                else:
                    base_qty = int(rng.integers(1, 5))

                qty_sold = min(avail, max(1, int(round(base_qty * season_mult))))
                sale_dt = m_start + timedelta(days=int(rng.integers(0, m_days)))
                discount = float(rng.choice([0.0, 0.0, 0.05, 0.10, 0.15, 0.20], p=[0.45, 0.15, 0.15, 0.12, 0.08, 0.05]))
                net_price = round(sprice * (1.0 - discount), 2)
                total_rev = round(qty_sold * net_price, 2)
                profit = round(total_rev - (qty_sold * ucost), 2)

                sale_id = f"SLS-{sale_counter:06d}"
                sale_counter += 1

                sales_rows.append({
                    "sales_id": sale_id,
                    "product_id": pid,
                    "warehouse_id": wid,
                    "sales_date": sale_dt.strftime("%Y-%m-%d"),
                    "quantity_sold": qty_sold,
                    "unit_price": sprice,
                    "discount": discount,
                    "total_revenue": total_rev,
                    "profit": profit,
                })

                mov_rows.append({
                    "movement_id": f"MOV-{mov_counter:06d}",
                    "product_id": pid,
                    "warehouse_id": wid,
                    "movement_date": sale_dt.strftime("%Y-%m-%d"),
                    "movement_type": "Sale",
                    "quantity": qty_sold,
                    "unit_cost": ucost,
                    "reference_id": sale_id,
                })
                mov_counter += 1
                stock_on_hand[(pid, wid)] -= qty_sold

                # Occasional return (~3% of sales)
                if rng.random() < 0.03 and qty_sold >= 2:
                    ret_qty = max(1, int(qty_sold // 4))
                    ret_dt = min(end_dt, sale_dt + timedelta(days=int(rng.integers(2, 12))))
                    mov_rows.append({
                        "movement_id": f"MOV-{mov_counter:06d}",
                        "product_id": pid,
                        "warehouse_id": wid,
                        "movement_date": ret_dt.strftime("%Y-%m-%d"),
                        "movement_type": "Return",
                        "quantity": ret_qty,
                        "unit_cost": ucost,
                        "reference_id": sale_id,
                    })
                    mov_counter += 1
                    stock_on_hand[(pid, wid)] += ret_qty

                # Replenishment check: skip replenishment for some stockout-prone SKUs in final months
                # to create realistic stockouts & reorder alerts
                skip_replenish = (260 <= p_num <= 405 and month_idx >= 18)
                if not skip_replenish and stock_on_hand[(pid, wid)] < max(10, reorder_lvl // 5):
                    order_qty = int(rng.integers(18, 48))
                    is_delayed = rng.random() < sup_delay_prob[sup_id]
                    delay_days = int(rng.integers(2, 12)) if is_delayed else int(rng.integers(-2, 1))
                    exp_dt = sale_dt + timedelta(days=lead)
                    act_dt = exp_dt + timedelta(days=delay_days)
                    po_id = f"PO-{po_counter:06d}"
                    po_counter += 1

                    if act_dt <= end_dt:
                        recv_qty = order_qty if rng.random() > 0.08 else max(1, int(order_qty * 0.85))
                        status = "Delivered" if recv_qty == order_qty else "Partial"
                        po_rows.append({
                            "purchase_order_id": po_id,
                            "supplier_id": sup_id,
                            "product_id": pid,
                            "warehouse_id": wid,
                            "order_date": sale_dt.strftime("%Y-%m-%d"),
                            "expected_delivery_date": exp_dt.strftime("%Y-%m-%d"),
                            "actual_delivery_date": act_dt.strftime("%Y-%m-%d"),
                            "quantity_ordered": order_qty,
                            "quantity_received": recv_qty,
                            "purchase_cost": round(recv_qty * ucost, 2),
                            "order_status": status,
                        })
                        mov_rows.append({
                            "movement_id": f"MOV-{mov_counter:06d}",
                            "product_id": pid,
                            "warehouse_id": wid,
                            "movement_date": act_dt.strftime("%Y-%m-%d"),
                            "movement_type": "Purchase",
                            "quantity": recv_qty,
                            "unit_cost": ucost,
                            "reference_id": po_id,
                        })
                        mov_counter += 1
                        stock_on_hand[(pid, wid)] += recv_qty
                    else:
                        # Open/Pending PO at period end
                        po_rows.append({
                            "purchase_order_id": po_id,
                            "supplier_id": sup_id,
                            "product_id": pid,
                            "warehouse_id": wid,
                            "order_date": sale_dt.strftime("%Y-%m-%d"),
                            "expected_delivery_date": exp_dt.strftime("%Y-%m-%d"),
                            "actual_delivery_date": None,
                            "quantity_ordered": order_qty,
                            "quantity_received": 0,
                            "purchase_cost": 0.0,
                            "order_status": "Pending",
                        })

        # Monthly inter-warehouse transfers & cycle-count adjustments (~15 each per month)
        for _ in range(12):
            prod = products_df.iloc[int(rng.integers(0, len(products_df)))]
            pid = prod["product_id"]
            ucost = float(prod["unit_cost"])
            src_wh, dst_wh = rng.choice(wh_ids, size=2, replace=False)
            avail = stock_on_hand[(pid, src_wh)]
            if avail >= 10:
                t_qty = int(rng.integers(3, min(20, avail // 2 + 1)))
                t_dt = m_start + timedelta(days=int(rng.integers(0, m_days)))
                ref = f"TRF-{month_idx:02d}-{mov_counter:05d}"
                mov_rows.append({
                    "movement_id": f"MOV-{mov_counter:06d}",
                    "product_id": pid,
                    "warehouse_id": src_wh,
                    "movement_date": t_dt.strftime("%Y-%m-%d"),
                    "movement_type": "Transfer Out",
                    "quantity": t_qty,
                    "unit_cost": ucost,
                    "reference_id": ref,
                })
                mov_counter += 1
                mov_rows.append({
                    "movement_id": f"MOV-{mov_counter:06d}",
                    "product_id": pid,
                    "warehouse_id": dst_wh,
                    "movement_date": t_dt.strftime("%Y-%m-%d"),
                    "movement_type": "Transfer In",
                    "quantity": t_qty,
                    "unit_cost": ucost,
                    "reference_id": ref,
                })
                mov_counter += 1
                stock_on_hand[(pid, src_wh)] -= t_qty
                stock_on_hand[(pid, dst_wh)] += t_qty

        for _ in range(8):
            prod = products_df.iloc[int(rng.integers(0, len(products_df)))]
            pid = prod["product_id"]
            ucost = float(prod["unit_cost"])
            wid = rng.choice(wh_ids)
            adj_qty = int(rng.integers(1, 5))
            adj_dt = m_start + timedelta(days=int(rng.integers(0, m_days)))
            mov_rows.append({
                "movement_id": f"MOV-{mov_counter:06d}",
                "product_id": pid,
                "warehouse_id": wid,
                "movement_date": adj_dt.strftime("%Y-%m-%d"),
                "movement_type": "Adjustment",
                "quantity": adj_qty,
                "unit_cost": ucost,
                "reference_id": f"ADJ-{month_idx:02d}-{mov_counter:05d}",
            })
            mov_counter += 1
            stock_on_hand[(pid, wid)] += adj_qty

    return (
        pd.DataFrame(po_rows),
        pd.DataFrame(mov_rows),
        pd.DataFrame(sales_rows),
    )


def inject_raw_data_issues(
    rng: np.random.Generator,
    products: pd.DataFrame,
    suppliers: pd.DataFrame,
    movements: pd.DataFrame,
    sales: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Inject realistic missing values, duplicates, casing issues, and outliers into raw CSVs."""
    p_raw = products.copy()
    s_raw = suppliers.copy()
    m_raw = movements.copy()
    sa_raw = sales.copy()

    # 1. Category casing / whitespace inconsistencies in products
    dirty_idx = rng.choice(p_raw.index, size=18, replace=False)
    for i, idx in enumerate(dirty_idx):
        val = str(p_raw.at[idx, "category"])
        p_raw.at[idx, "category"] = val.lower() + " " if i % 2 == 0 else val.upper()
    # Missing brands
    p_raw.loc[rng.choice(p_raw.index, size=8, replace=False), "brand"] = np.nan

    # 2. Missing supplier ratings
    s_raw.loc[rng.choice(s_raw.index, size=3, replace=False), "supplier_rating"] = np.nan

    # 3. Missing unit_cost in a few movements + duplicate movement rows
    m_raw.loc[rng.choice(m_raw.index, size=15, replace=False), "unit_cost"] = np.nan
    m_dups = m_raw.sample(n=35, random_state=config.RANDOM_SEED)
    m_raw = pd.concat([m_raw, m_dups], ignore_index=True)

    # 4. Missing discount, negative quantity invalid rows, extreme outlier, and duplicates in sales
    sa_raw.loc[rng.choice(sa_raw.index, size=40, replace=False), "discount"] = np.nan
    bad_neg_idx = rng.choice(sa_raw.index, size=5, replace=False)
    sa_raw.loc[bad_neg_idx, "quantity_sold"] = -3
    outlier_idx = rng.choice(sa_raw.index.difference(bad_neg_idx), size=4, replace=False)
    sa_raw.loc[outlier_idx, "quantity_sold"] = 9999
    sa_dups = sa_raw.sample(n=45, random_state=config.RANDOM_SEED)
    sa_raw = pd.concat([sa_raw, sa_dups], ignore_index=True)

    return p_raw, s_raw, m_raw, sa_raw


def generate_all_datasets(output_dir: Path | None = None) -> dict[str, pd.DataFrame]:
    """Generate and save all 6 raw CSV datasets."""
    out_dir = output_dir or config.RAW_DATA_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
